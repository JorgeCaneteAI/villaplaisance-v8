<?php
declare(strict_types=1);

/**
 * bin/build_lucide_sprite.php
 *
 * Télécharge un set curated d'icônes Lucide (MIT, https://lucide.dev)
 * pertinentes pour le tourisme + hôtellerie, et les agrège dans un sprite
 * SVG monobloc `public/assets/img/icons-lucide.svg`.
 *
 * Convention d'ID : `icon-lc-<name>` (préfixe lc pour distinguer du sprite
 * custom existant `icon-<name>` qui contient les icônes thématiques
 * spécifiques Villa Plaisance — vignoble, aqueduc, superhost, etc.).
 *
 * Stroke harmonisé à 1.5 (cohérent avec le sprite custom).
 *
 * Lancement (local, Mac) :
 *   cd "/Users/jorgecanete/Documents/C.L.A.U.D.E/villaplaisance/Site Internet/v8" && \
 *   php bin/build_lucide_sprite.php
 *
 * Le sprite généré est commité dans git, pas besoin de relancer côté serveur.
 */

$ROOT = dirname(__DIR__);
$cdn = 'https://unpkg.com/lucide-static@latest/icons/';
$out = $ROOT . '/public/assets/img/icons-lucide.svg';

// ──────────────────────────────────────────────────────────────────────
// Catalogue curated tourisme + hôtellerie (par catégorie).
// L'ordre ici sert aussi à la page admin icons-lab pour le tri/affichage.
// ──────────────────────────────────────────────────────────────────────
$catalog = [
    'hebergement' => [
        'bed-double', 'bed-single', 'bed', 'hotel', 'key', 'key-round',
        'accessibility', 'baby',
    ],
    'confort' => [
        'wifi', 'tv', 'monitor', 'air-vent', 'fan',
        'thermometer-sun', 'thermometer-snowflake', 'plug-zap', 'lamp', 'lightbulb',
    ],
    'salle_de_bain' => [
        'shower-head', 'bath', 'droplet', 'droplets',
    ],
    'cuisine' => [
        'coffee', 'utensils', 'utensils-crossed', 'wine', 'beer',
        'croissant', 'cake', 'soup', 'refrigerator', 'chef-hat',
    ],
    'nature' => [
        'tree-deciduous', 'tree-pine', 'trees', 'leaf', 'flower', 'flower-2',
        'sprout', 'sun', 'mountain', 'palmtree',
    ],
    'activites' => [
        'waves', 'bike', 'footprints', 'music', 'book', 'camera', 'palette',
    ],
    'transport' => [
        'car', 'plane', 'train', 'bus', 'parking-circle',
    ],
    'animaux' => [
        'dog', 'cat', 'paw-print',
    ],
    'famille' => [
        'users',
    ],
    'avis' => [
        'star', 'heart', 'thumbs-up', 'quote',
    ],
    'contact' => [
        'mail', 'phone', 'message-circle', 'calendar', 'clock',
        'map-pin', 'map', 'navigation',
    ],
    'saison' => [
        'sunrise', 'sunset', 'snowflake', 'umbrella', 'cloud-sun',
    ],
];

$allIcons = [];
foreach ($catalog as $category => $icons) {
    foreach ($icons as $name) {
        $allIcons[] = ['name' => $name, 'category' => $category];
    }
}

$totalRequested = count($allIcons);
echo "Building Lucide sprite — {$totalRequested} icons across " . count($catalog) . " categories.\n\n";

$xml  = '<?xml version="1.0" encoding="UTF-8"?>' . "\n";
$xml .= '<!-- Generated by bin/build_lucide_sprite.php — DO NOT EDIT manually. -->' . "\n";
$xml .= '<!-- Source : Lucide v1.x (ISC license, https://lucide.dev/license) -->' . "\n";
$xml .= '<svg xmlns="http://www.w3.org/2000/svg" style="display:none;">' . "\n";

$ok = 0;
$fail = 0;

foreach ($allIcons as $entry) {
    $name = $entry['name'];
    $url = $cdn . $name . '.svg';

    $raw = @file_get_contents($url);
    if ($raw === false) {
        echo "  ✗ {$name} (download failed)\n";
        $fail++;
        continue;
    }

    // Extrait le contenu entre <svg ...> et </svg>
    if (!preg_match('#<svg[^>]*>(.+?)</svg>#s', $raw, $m)) {
        echo "  ✗ {$name} (no <svg> found)\n";
        $fail++;
        continue;
    }

    $inner = trim($m[1]);
    // Nettoie les commentaires et compacte les whitespaces multiples.
    $inner = preg_replace('/<!--.*?-->/s', '', $inner);
    $inner = preg_replace('/\s+/', ' ', $inner);
    $inner = trim($inner);

    $xml .= sprintf(
        '  <symbol id="icon-lc-%s" viewBox="0 0 24 24" fill="none" stroke="currentColor" stroke-width="1.5" stroke-linecap="round" stroke-linejoin="round">%s</symbol>' . "\n",
        $name,
        $inner
    );
    echo "  ✓ {$name}\n";
    $ok++;
}

$xml .= '</svg>' . "\n";
file_put_contents($out, $xml);

echo "\nDone — {$ok} OK, {$fail} failed → " . basename($out)
    . ' (' . number_format(strlen($xml) / 1024, 1, ',', ' ') . " Ko)\n";

// Exporte aussi le catalogue + métadonnées en JSON pour la page admin.
$meta = ['catalog' => $catalog, 'generated_at' => date('c'), 'source' => 'lucide-static@latest'];
$metaPath = $ROOT . '/public/assets/img/icons-lucide.json';
file_put_contents($metaPath, json_encode($meta, JSON_PRETTY_PRINT | JSON_UNESCAPED_SLASHES));
echo "Catalogue : " . basename($metaPath) . "\n";
